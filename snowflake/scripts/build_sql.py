"""Generate the derived Snowflake SQL files.

    python snowflake/scripts/build_sql.py

Writes:
  snowflake/sql/02_seed.sql            from shared/seed (+ synthetic history)
  snowflake/sql/04_pas_procedures.sql  template + shared criteria engine
  snowflake/sql/05_ai.sql              template + criteria engine + Cortex extractor

Single source of truth: the criteria engine in
services/common/authbridge_common/criteria.py runs in the local mock backend and
is embedded verbatim in the Snowflake Python stored procedures.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(ROOT / "services" / "common"), str(ROOT / "services" / "provider")]

from authbridge_common import history  # noqa: E402
from authbridge_common.seed import load_seed, policy_sections  # noqa: E402
from provider_service import builders as B  # noqa: E402

SQL = ROOT / "snowflake" / "sql"
TPL = ROOT / "snowflake" / "templates"


def lit(v):
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "TRUE" if v else "FALSE"
    if isinstance(v, (int, float)):
        return repr(v)
    s = str(v)
    assert "$$" not in s, "seed text must not contain $$"
    return "$$" + s + "$$"


def js(v):
    return "PARSE_JSON(%s)" % lit(json.dumps(v))


def insert(table, rows, json_cols=()):
    if not rows:
        return ""
    cols = list(rows[0].keys())
    out = []
    for r in rows:
        vals = [js(r[c]) if c in json_cols else lit(r[c]) for c in cols]
        out.append("INSERT INTO %s (%s) SELECT %s;" % (table, ", ".join(cols), ", ".join(vals)))
    return "\n".join(out) + "\n"


def build_seed():
    seed = load_seed(ROOT / "shared" / "seed")
    ehr, payer = seed["ehr"], seed["payer"]
    parts = [
        "-- =============================================================================",
        "-- AuthBridge 02 — seed data. GENERATED by snowflake/scripts/build_sql.py.",
        "-- Re-running resets the demo: it truncates and reloads every seeded table,",
        "-- including PA requests and decisions.",
        "-- =============================================================================",
        "USE ROLE AUTHBRIDGE_ADMIN;", "USE DATABASE AUTHBRIDGE;", "USE WAREHOUSE AUTHBRIDGE_APP_WH;", "",
    ]
    tables = ["CORE.PATIENT", "CORE.COVERAGE", "CORE.PRACTITIONER", "CORE.CLINICAL_DOCUMENT", "PROVIDER.EHR_ORDER",
              "PAYER.PAYER_PLAN", "PAYER.MEMBER_ELIGIBILITY", "PAYER.SERVICE_PA_RULES", "PAYER.QUESTIONNAIRE",
              "PAYER.POLICY_CRITERIA", "PAYER.GOLD_CARD_STATUS", "PAYER.PA_REQUEST", "PAYER.DECISION", "PAYER.APPEAL",
              "PAYER.QUESTIONNAIRE_RESPONSE", "PAYER.SUBMITTED_DOCUMENT", "PAYER.CRD_RESPONSE", "PAYER.SUBSCRIPTION",
              "AI.POLICY_DOC_CHUNKS", "AI.CLINICAL_REVIEW", "AI.AI_REVIEW_RESULT", "RAW.FHIR_RAW_BUNDLES"]
    parts += ["TRUNCATE TABLE IF EXISTS %s;" % t for t in tables] + [""]

    patients, coverages = [], []
    for p in ehr["patients"]:
        patients.append({"patient_id": p["patient_id"], "mrn": p["mrn"], "given": p["given"], "family": p["family"],
                         "birth_date": p["birth_date"], "gender": p["gender"], "city": p["city"], "state": p["state"],
                         "problems": p["problems"], "demo_scenario": p["scenario"], "suggested_order": p["suggested_order"],
                         "suggested_reason": p["suggested_reason"], "fhir": B.patient_resource(p)})
        c = p["coverage"]
        coverages.append({"coverage_id": c["coverage_id"], "patient_id": p["patient_id"], "payer_id": payer["payer"]["payer_id"],
                          "member_id": c["member_id"], "plan_id": c["plan_id"], "status": "active",
                          "period_start": c["period_start"], "period_end": c["period_end"], "fhir": B.coverage_resource(p)})
    parts.append(insert("CORE.PATIENT", patients, json_cols=("problems", "fhir")))
    parts.append(insert("CORE.COVERAGE", coverages, json_cols=("fhir",)))
    parts.append(insert("CORE.PRACTITIONER", [{k: pr[k] for k in ("practitioner_role_id", "practitioner_id", "npi", "name", "specialty")}
                                              for pr in ehr["practitioners"]]))
    parts.append(insert("CORE.CLINICAL_DOCUMENT", [
        {"doc_id": n["doc_id"], "patient_id": n["patient_id"], "note_type": n["note_type"], "encounter_date": n["encounter_date"],
         "author_npi": n["author_npi"], "title": n["title"], "text": n["text"], "attach_on_request": bool(n.get("attach_on_request"))}
        for n in ehr["notes"]]))

    parts.append(insert("PAYER.PAYER_PLAN", payer["plans"]))
    parts.append(insert("PAYER.MEMBER_ELIGIBILITY", payer["members"]))
    parts.append(insert("PAYER.SERVICE_PA_RULES", payer["service_pa_rules"]))
    parts.append(insert("PAYER.QUESTIONNAIRE", [
        {"questionnaire_id": q["id"], "version": q["version"], "canonical_url": q["url"], "title": q["title"], "fhir": q}
        for q in seed["questionnaires"].values()], json_cols=("fhir",)))
    parts.append(insert("PAYER.POLICY_CRITERIA", [dict(n) for n in payer["policy_criteria"]], json_cols=("threshold",)))
    parts.append(insert("PAYER.GOLD_CARD_STATUS", payer["gold_card_status"]))

    service_by_policy = {r["policy_doc_id"]: r["service_code"] for r in payer["service_pa_rules"] if r["policy_doc_id"]}
    chunks = []
    for pid, md in seed["policies"].items():
        for i, s in enumerate(policy_sections(pid, md)):
            chunks.append({"chunk_id": "%s#%02d" % (pid, i), "policy_doc_id": pid, "payer_id": payer["payer"]["payer_id"],
                           "service_code": service_by_policy.get(pid), "section_id": s["section_id"],
                           "section_title": s["section_title"], "effective_date": "2026-01-01", "chunk_text": s["text"]})
    parts.append(insert("AI.POLICY_DOC_CHUNKS", chunks))

    hist = history.generate()
    parts.append("-- Synthetic history so analytics has data on day 1 (same generator as mock mode)")
    parts.append(insert("PAYER.PA_REQUEST", [
        {"pa_id": h["pa_id"], "claim_id": None, "patient_id": h["patient_id"], "member_id": h["member_id"], "plan_id": h["plan_id"],
         "line_of_business": "MA" if h["plan_id"] == "DEMO-MA-01" else "COMMERCIAL", "ordering_npi": h["ordering_npi"],
         "service_code": h["service_code"], "code_system": h["code_system"], "service_display": h["service_display"],
         "policy_doc_id": h["policy_doc_id"], "priority": h["priority"], "status": h["status"], "recommendation": h["recommendation"],
         "submitted_at": h["submitted_at"], "sla_due_at": h["sla_due_at"], "updated_at": h["decided_at"], "is_historical": True}
        for h in hist]))
    parts.append(insert("PAYER.DECISION", [
        {"pa_id": h["pa_id"], "review_action_code": h["review_action_code"], "decided_by": h["decided_by"],
         "decider_role": h["decider_role"], "ai_assisted": True, "decided_at": h["decided_at"]} for h in hist]))
    parts.append(insert("PAYER.APPEAL", [
        {"pa_id": h["pa_id"], "filed_at": h["decided_at"], "outcome": h["appeal_outcome"], "resolved_at": h["decided_at"]}
        for h in hist if h["appealed"]]))
    (SQL / "02_seed.sql").write_text("\n".join(parts), encoding="utf-8")


def build_templates():
    engine = (ROOT / "services" / "common" / "authbridge_common" / "criteria.py").read_text()
    helpers = (TPL / "sp_helpers.py").read_text()
    extract = (TPL / "cortex_extract.py").read_text()
    for src, dst in (("04_pas_procedures.sql.tmpl", "04_pas_procedures.sql"), ("05_ai.sql.tmpl", "05_ai.sql")):
        text = (TPL / src).read_text()
        text = text.replace("{{CRITERIA_ENGINE}}", engine).replace("{{SP_HELPERS}}", helpers).replace("{{CORTEX_EXTRACT}}", extract)
        assert "{{" not in text, "unfilled placeholder in %s" % src
        body_check = text.split("$$")
        assert len(body_check) % 2 == 1, "unbalanced $$ in %s" % dst
        (SQL / dst).write_text(text, encoding="utf-8")


if __name__ == "__main__":
    build_seed()
    build_templates()
    print("Wrote 02_seed.sql, 04_pas_procedures.sql, 05_ai.sql in", SQL)
