USE ROLE ACCOUNTADMIN;

-- Claude models in Cortex are reached through cross-region inference in most
-- regions. Pick the narrowest scope your organisation accepts.
-- ALTER ACCOUNT SET CORTEX_ENABLED_CROSS_REGION = 'AWS_US';

CREATE DATABASE IF NOT EXISTS AUTHBRIDGE COMMENT = 'AuthBridge ePA hackathon (synthetic data only)';
CREATE SCHEMA IF NOT EXISTS AUTHBRIDGE.RAW       COMMENT = 'Every inbound/outbound FHIR and CDS Hooks payload as VARIANT';
CREATE SCHEMA IF NOT EXISTS AUTHBRIDGE.CORE      COMMENT = 'EHR chart data: patients, coverage, practitioners, notes';
CREATE SCHEMA IF NOT EXISTS AUTHBRIDGE.PROVIDER  COMMENT = 'EHR order workflow state';
CREATE SCHEMA IF NOT EXISTS AUTHBRIDGE.PAYER     COMMENT = 'Payer rules, PA requests, decisions';
CREATE SCHEMA IF NOT EXISTS AUTHBRIDGE.AI        COMMENT = 'Cortex Search, agents, AI procedures, audit';
CREATE SCHEMA IF NOT EXISTS AUTHBRIDGE.ANALYTICS COMMENT = 'Metrics views and semantic view';

-- One small warehouse for the app path (keep it warm during demos),
-- one for AI/tasks/analytics so a long agent call never blocks order-sign.
CREATE WAREHOUSE IF NOT EXISTS AUTHBRIDGE_APP_WH WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 300 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
CREATE WAREHOUSE IF NOT EXISTS AUTHBRIDGE_AI_WH  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 120 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

-- ---------------------------------------------------------------------------
-- Roles (PRD 9.4). Personas are used for governance demos; the two service
-- roles are what the local services log in with.
-- ---------------------------------------------------------------------------
USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS AUTHBRIDGE_ADMIN;
CREATE ROLE IF NOT EXISTS AUTHBRIDGE_PROVIDER_SVC_ROLE;
CREATE ROLE IF NOT EXISTS AUTHBRIDGE_PAYER_SVC_ROLE;
CREATE ROLE IF NOT EXISTS PROVIDER_ROLE;
CREATE ROLE IF NOT EXISTS UM_NURSE_ROLE;
CREATE ROLE IF NOT EXISTS MEDICAL_DIRECTOR_ROLE;
CREATE ROLE IF NOT EXISTS PAYER_ANALYST_ROLE;

GRANT ROLE AUTHBRIDGE_PROVIDER_SVC_ROLE TO ROLE AUTHBRIDGE_ADMIN;
GRANT ROLE AUTHBRIDGE_PAYER_SVC_ROLE    TO ROLE AUTHBRIDGE_ADMIN;
GRANT ROLE PROVIDER_ROLE, UM_NURSE_ROLE, MEDICAL_DIRECTOR_ROLE, PAYER_ANALYST_ROLE TO ROLE AUTHBRIDGE_ADMIN;
GRANT ROLE AUTHBRIDGE_ADMIN TO ROLE SYSADMIN;
GRANT ROLE AUTHBRIDGE_ADMIN TO USER <YOUR_USER>;

USE ROLE ACCOUNTADMIN;
GRANT OWNERSHIP ON DATABASE AUTHBRIDGE TO ROLE AUTHBRIDGE_ADMIN COPY CURRENT GRANTS;
GRANT OWNERSHIP ON ALL SCHEMAS IN DATABASE AUTHBRIDGE TO ROLE AUTHBRIDGE_ADMIN COPY CURRENT GRANTS;
GRANT USAGE ON WAREHOUSE AUTHBRIDGE_APP_WH TO ROLE AUTHBRIDGE_ADMIN;
GRANT USAGE ON WAREHOUSE AUTHBRIDGE_AI_WH  TO ROLE AUTHBRIDGE_ADMIN;
GRANT OPERATE ON WAREHOUSE AUTHBRIDGE_APP_WH TO ROLE AUTHBRIDGE_ADMIN;
GRANT OPERATE ON WAREHOUSE AUTHBRIDGE_AI_WH TO ROLE AUTHBRIDGE_ADMIN;
GRANT CREATE INTEGRATION ON ACCOUNT TO ROLE AUTHBRIDGE_ADMIN;
GRANT EXECUTE TASK ON ACCOUNT TO ROLE AUTHBRIDGE_ADMIN;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE AUTHBRIDGE_ADMIN;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE AUTHBRIDGE_PROVIDER_SVC_ROLE;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE AUTHBRIDGE_PAYER_SVC_ROLE;

