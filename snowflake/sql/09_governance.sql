-- ---------------------------------------------------------------- tags
CREATE TAG IF NOT EXISTS CORE.PHI_CLASS ALLOWED_VALUES 'NAME', 'DOB', 'MRN', 'ADDRESS', 'CLINICAL_TEXT'
  COMMENT = 'Protected health information category';

-- ---------------------------------------------------------------- masking
-- Personas outside the care team or UM see masked identifiers.
CREATE OR REPLACE MASKING POLICY CORE.MASK_PHI_STRING AS (val STRING) RETURNS STRING ->
  CASE WHEN IS_ROLE_IN_SESSION('AUTHBRIDGE_ADMIN') OR IS_ROLE_IN_SESSION('PROVIDER_ROLE')
         OR IS_ROLE_IN_SESSION('AUTHBRIDGE_PROVIDER_SVC_ROLE') OR IS_ROLE_IN_SESSION('UM_NURSE_ROLE')
         OR IS_ROLE_IN_SESSION('MEDICAL_DIRECTOR_ROLE') OR IS_ROLE_IN_SESSION('AUTHBRIDGE_PAYER_SVC_ROLE')
       THEN val ELSE '***MASKED***' END;

CREATE OR REPLACE MASKING POLICY CORE.MASK_PHI_DATE AS (val DATE) RETURNS DATE ->
  CASE WHEN IS_ROLE_IN_SESSION('AUTHBRIDGE_ADMIN') OR IS_ROLE_IN_SESSION('PROVIDER_ROLE')
         OR IS_ROLE_IN_SESSION('AUTHBRIDGE_PROVIDER_SVC_ROLE') OR IS_ROLE_IN_SESSION('UM_NURSE_ROLE')
         OR IS_ROLE_IN_SESSION('MEDICAL_DIRECTOR_ROLE')
       THEN val ELSE DATE_FROM_PARTS(YEAR(val), 1, 1) END;    -- analysts see birth year only

-- Tag-based masking: everything tagged NAME/MRN/ADDRESS gets the string policy.
ALTER TAG CORE.PHI_CLASS SET MASKING POLICY CORE.MASK_PHI_STRING;

ALTER TABLE CORE.PATIENT MODIFY COLUMN given  SET TAG CORE.PHI_CLASS = 'NAME';
ALTER TABLE CORE.PATIENT MODIFY COLUMN family SET TAG CORE.PHI_CLASS = 'NAME';
ALTER TABLE CORE.PATIENT MODIFY COLUMN mrn    SET TAG CORE.PHI_CLASS = 'MRN';
ALTER TABLE CORE.PATIENT MODIFY COLUMN city   SET TAG CORE.PHI_CLASS = 'ADDRESS';
ALTER TABLE CORE.PATIENT MODIFY COLUMN birth_date SET MASKING POLICY CORE.MASK_PHI_DATE;

-- ---------------------------------------------------------------- row access
-- Reviewers and the services see every request; an analyst sees only the lines
-- of business mapped to their role (demo: the analyst persona sees MA only).
CREATE TABLE IF NOT EXISTS PAYER.LOB_ACCESS (role_name STRING, line_of_business STRING);
MERGE INTO PAYER.LOB_ACCESS t USING (SELECT 'PAYER_ANALYST_ROLE' AS role_name, 'MA' AS line_of_business) s
  ON t.role_name = s.role_name AND t.line_of_business = s.line_of_business
  WHEN NOT MATCHED THEN INSERT VALUES (s.role_name, s.line_of_business);

CREATE OR REPLACE ROW ACCESS POLICY PAYER.RAP_PA_BY_LOB AS (lob STRING) RETURNS BOOLEAN ->
  IS_ROLE_IN_SESSION('AUTHBRIDGE_ADMIN') OR IS_ROLE_IN_SESSION('AUTHBRIDGE_PAYER_SVC_ROLE')
  OR IS_ROLE_IN_SESSION('UM_NURSE_ROLE') OR IS_ROLE_IN_SESSION('MEDICAL_DIRECTOR_ROLE')
  OR EXISTS (SELECT 1 FROM PAYER.LOB_ACCESS a WHERE IS_ROLE_IN_SESSION(a.role_name) AND a.line_of_business = lob);
ALTER TABLE PAYER.PA_REQUEST ADD ROW ACCESS POLICY PAYER.RAP_PA_BY_LOB ON (line_of_business);

